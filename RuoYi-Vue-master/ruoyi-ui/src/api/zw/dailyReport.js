import request from '@/utils/request'

export function listDailyReport(query) {
  return request({ url: '/zw/dailyReport/list', method: 'get', params: query })
}

export function getDailyReport(reportId) {
  return request({ url: '/zw/dailyReport/' + reportId, method: 'get' })
}

export function addDailyReport(data) {
  return request({ url: '/zw/dailyReport', method: 'post', data: data })
}

export function updateDailyReport(data) {
  return request({ url: '/zw/dailyReport', method: 'put', data: data })
}

export function delDailyReport(reportIds) {
  return request({ url: '/zw/dailyReport/' + reportIds, method: 'delete' })
}

export function autoGenerateDailyReport() {
  return request({ url: '/zw/dailyReport/autoGenerate', method: 'post' })
}
